//! The shape of a catalogue entry. `catalogue.zig` is generated against it.

pub const Status = enum {
    /// Built and tested by this repository's CI.
    ok,
    /// Catalogued and fetchable, not yet built by CI.
    untested,
    /// Not built; `reason` says why.
    excluded,
};

pub const Source = enum {
    /// nvim-treesitter's `runtime/queries`, Apache-2.0. Neovim's dialect.
    nvim,
    /// This repository's `queries/`, MIT. tree-sitter's dialect.
    ztreesitter,
    /// The grammar's own repository, under the grammar's licence.
    /// tree-sitter's dialect.
    grammar,
    /// Helix's `runtime/queries`, MPL-2.0. tree-sitter's dialect.
    helix,
};

pub const QueryFile = struct {
    source: Source,
    /// Relative to the source's root: nvim-treesitter's or Helix's repository,
    /// this repository, or the grammar's mirror.
    path: []const u8,
};

/// Files concatenated in order make one query. Inheritance is already
/// resolved: an inherited language's files come first.
pub const Queries = struct {
    highlights: []const QueryFile = &.{},
    injections: []const QueryFile = &.{},
    locals: []const QueryFile = &.{},
    folds: []const QueryFile = &.{},
    indents: []const QueryFile = &.{},
    tags: []const QueryFile = &.{},
};

pub const Grammar = struct {
    /// nvim-treesitter's name, which is also the language name in queries.
    name: []const u8,
    /// The `const TSLanguage *(void)` function `parser.c` exports.
    symbol: []const u8,
    url: []const u8,
    /// As nvim-treesitter spells it: a commit or a tag.
    revision: []const u8,
    commit: []const u8,
    /// The grammar's directory inside the repository, or "".
    location: []const u8,
    scanner: bool,
    /// `LANGUAGE_VERSION` in `parser.c`.
    abi: u8,
    /// `parser.c` was generated by tools/catalogue.py.
    generated: bool,
    /// The commit in this repository holding the grammar's mirror.
    mirror: []const u8,
    /// nvim-treesitter's tier: 1 stable, 2 unstable, 3 unmaintained.
    tier: u8,
    /// SPDX identifier, or "unknown".
    licence: []const u8,
    licence_file: []const u8,
    licence_note: []const u8,
    /// Anything else the catalogue tool found worth saying.
    notes: []const u8,
    /// Languages nvim-treesitter installs with this one.
    requires: []const []const u8,
    status: Status,
    reason: []const u8,
    queries: Queries,
};
